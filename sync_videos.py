#!/usr/bin/env python3
"""Keeps videos.js in sync with your YouTube channel (standard library only).

What it does each run:
  1. reads every video link in links.js
  2. reads your channel's public RSS feed (your newest ~15 uploads)
  3. looks up title, channel name and "is it a Short?" for anything new
  4. writes videos.js, which the page loads instantly (no lookups in visitors' browsers)

Run it by hand:   python3 sync_videos.py
It also runs by itself on GitHub (see .github/workflows/sync-videos.yml).
"""
import json
import pathlib
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET

HERE = pathlib.Path(__file__).resolve().parent
CHANNEL_ID = "UCQL8GLFAW2RzhF_TjI5-7Dw"          # change this if you ever move to another channel
FEED_URL = f"https://www.youtube.com/feeds/videos.xml?channel_id={CHANNEL_ID}"
UA = "Mozilla/5.0 (compatible; quran-shorts-sync/1.0)"
ID_RE = re.compile(r"(?:youtube\.com/(?:shorts/|embed/|live/)|youtu\.be/|[?&]v=)([\w-]{11})")
HEADER = ("/* AUTO-GENERATED by sync_videos.py. Do not edit by hand.\n"
          "   Titles and channel names let the page load instantly; thumbnails come from YouTube itself. */\n")


# ---------------------------------------------------------------- network (replaced in tests)
def http_get(url, timeout=20, retries=2):
    for attempt in range(retries + 1):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept-Language": "en"})
            with urllib.request.urlopen(req, timeout=timeout) as r:
                return r.read()
        except Exception as e:                                   # noqa: BLE001
            if attempt == retries:
                print(f"  ! could not fetch {url[:80]}: {e}", file=sys.stderr)
                return None
            time.sleep(1.5 * (attempt + 1))


def oembed(vid):
    """(title, channel) from YouTube's oEmbed, falling back to noembed. None if both fail."""
    watch = "https://www.youtube.com/watch?v=" + vid
    for base in ("https://www.youtube.com/oembed?format=json&url=",
                 "https://noembed.com/embed?url="):
        raw = http_get(base + urllib.parse.quote(watch, safe=""), retries=1)
        if not raw:
            continue
        try:
            j = json.loads(raw.decode("utf-8"))
        except ValueError:
            continue
        if j.get("title"):
            return j["title"], j.get("author_name", "")
    return None


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *a, **k):
        return None


def is_short(vid):
    """True/False, or None if it cannot be told. /shorts/ID answers 200 for Shorts, redirects for normal videos."""
    opener = urllib.request.build_opener(_NoRedirect)
    req = urllib.request.Request("https://www.youtube.com/shorts/" + vid, headers={"User-Agent": UA}, method="HEAD")
    try:
        with opener.open(req, timeout=15) as r:
            return r.status == 200
    except urllib.error.HTTPError as e:
        return False if 300 <= e.code < 400 else None
    except Exception:                                            # noqa: BLE001
        return None


# ---------------------------------------------------------------- parsing
def strip_comments(js):
    js = re.sub(r"/\*.*?\*/", "", js, flags=re.S)
    return re.sub(r"(?m)(?<!:)//[^\n]*", "", js)


def ids_in(text):
    out = []
    for m in ID_RE.finditer(text):
        if m.group(1) not in out:
            out.append(m.group(1))
    return out


def read_links(path):
    """(video ids in SHORTS/LESSONS, ids in HIDDEN)"""
    if not path.exists():
        return [], set()
    js = strip_comments(path.read_text(encoding="utf-8"))
    hidden = set()
    m = re.search(r"window\.HIDDEN\s*=\s*\[(.*?)\]", js, re.S)
    if m:
        body = m.group(1)
        hidden = set(ids_in(body)) | set(re.findall(r"""["']([\w-]{11})["']""", body))
        js = js.replace(m.group(0), "")
    return [i for i in ids_in(js) if i not in hidden], hidden


def parse_feed(raw):
    ns = {"a": "http://www.w3.org/2005/Atom", "yt": "http://www.youtube.com/xml/schemas/2015"}
    out = []
    try:
        root = ET.fromstring(raw)
    except ET.ParseError:
        return out
    for e in root.findall("a:entry", ns):
        vid = e.findtext("yt:videoId", default="", namespaces=ns)
        if not vid:
            continue
        out.append({"id": vid,
                    "t": (e.findtext("a:title", default="", namespaces=ns) or "").strip(),
                    "a": (e.findtext("a:author/a:name", default="", namespaces=ns) or "").strip(),
                    "p": (e.findtext("a:published", default="", namespaces=ns) or "").strip()})
    return out


def load_videos(path):
    if not path.exists():
        return []
    txt = path.read_text(encoding="utf-8")
    i, j = txt.find("["), txt.rfind("]")
    if i < 0 or j < i:
        return []
    try:
        return [v for v in json.loads(txt[i:j + 1]) if isinstance(v, dict) and v.get("id")]
    except ValueError:
        return []


def render_videos(rows):
    lines = []
    for v in sorted(rows, key=lambda r: r["id"]):
        row = {"id": v["id"], "t": v.get("t", ""), "a": v.get("a", "")}
        if isinstance(v.get("s"), bool):
            row["s"] = v["s"]
        row["p"] = v.get("p", "")
        row["auto"] = bool(v.get("auto"))
        s = json.dumps(row, ensure_ascii=False, separators=(",", ":"))
        lines.append("  " + s.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029"))
    return HEADER + "window.VIDEOS = [\n" + ",\n".join(lines) + "\n];\n"


# ---------------------------------------------------------------- main
def sync(root=HERE, pause=0.15):
    links_path, videos_path = root / "links.js", root / "videos.js"
    link_ids, hidden = read_links(links_path)
    existing = {v["id"]: v for v in load_videos(videos_path)}

    raw = http_get(FEED_URL)
    feed = parse_feed(raw) if raw else []
    print(f"links.js: {len(link_ids)} videos · channel feed: {len(feed)} newest uploads · already known: {len(existing)}")

    out = {}
    for vid in link_ids:                                         # videos you listed yourself
        out[vid] = dict(existing.get(vid, {}), id=vid, auto=existing.get(vid, {}).get("auto", False))
    for f in feed:                                               # new uploads found automatically
        if f["id"] in hidden:
            continue
        cur = dict(existing.get(f["id"], {}), id=f["id"])
        cur["t"] = f["t"] or cur.get("t", "")
        cur["a"] = f["a"] or cur.get("a", "")
        cur["p"] = f["p"] or cur.get("p", "")
        cur["auto"] = True
        out[f["id"]] = out.get(f["id"], {}) | cur
    for vid, v in existing.items():                              # keep earlier auto-found videos
        if vid not in out and v.get("auto") and vid not in hidden:
            out[vid] = v

    added = failed = 0
    for vid, v in out.items():
        if not v.get("t"):
            got = oembed(vid)
            time.sleep(pause)
            if got:
                v["t"], v["a"] = got[0], got[1] or v.get("a", "")
                added += 1
            else:
                failed += 1
                print(f"  ! no title for {vid} (will retry next run)", file=sys.stderr)
        if "s" not in v:
            s = is_short(vid)
            time.sleep(pause)
            if s is not None:
                v["s"] = s                                       # unknown stays unset and is retried next run
    for v in out.values():
        v.setdefault("p", "")

    new_text = render_videos(list(out.values()))
    old_text = videos_path.read_text(encoding="utf-8") if videos_path.exists() else ""
    if new_text != old_text:
        videos_path.write_text(new_text, encoding="utf-8")
        print(f"videos.js updated: {len(out)} videos ({added} new titles fetched, {failed} failed)")
        return True
    print(f"videos.js already up to date ({len(out)} videos)")
    return False


if __name__ == "__main__":
    sync()
